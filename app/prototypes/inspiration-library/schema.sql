-- =====================================================================
-- Inspiration library: every database table this prototype needs.
--
-- ALREADY SET UP: your Supabase project has these tables. They were created
-- from the four migration files in db/migrations/ (in the project's top
-- folder), applied in order with the Supabase MCP. Those files are the
-- official record of the database; this file is the same SQL gathered in one
-- place, so you can read it top to bottom. Don't run it on your current
-- project: it stops with "relation already exists", because the tables are
-- already there.
--
-- For a NEW, empty Supabase project, either apply db/migrations/0001 to 0004
-- in order, or paste this whole file into Supabase → SQL Editor → New query
-- → Run. It's one transaction (begin … commit): if any line fails, nothing
-- is created, so you can fix the problem and run it again from a clean slate.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- PART 1 · Better Auth's tables
--
-- Generated by Better Auth 1.7.12's own migration code for the settings in
-- lib/auth.ts (Postgres, email and password, rate limits stored in the
-- database), so they match exactly what Better Auth expects. Don't rename
-- anything here. "user" is in quotes because `user` is a reserved word
-- in Postgres.
--
--   user          one row per person: name, email
--   account       how they sign in; for email and password, this holds
--                 the HASHED password (never the password itself)
--   session       one row per signed-in browser; the cookie holds its token
--   verification  short-lived codes (used by email verification and
--                 password reset, if you add them later)
--   rateLimit     counts recent sign-in attempts per IP address
-- ---------------------------------------------------------------------

create table "user" ("id" text not null primary key, "name" text not null, "email" text not null unique, "emailVerified" boolean not null, "image" text, "createdAt" timestamptz default CURRENT_TIMESTAMP not null, "updatedAt" timestamptz default CURRENT_TIMESTAMP not null);

create table "session" ("id" text not null primary key, "expiresAt" timestamptz not null, "token" text not null unique, "createdAt" timestamptz default CURRENT_TIMESTAMP not null, "updatedAt" timestamptz not null, "ipAddress" text, "userAgent" text, "userId" text not null references "user" ("id") on delete cascade);

create table "account" ("id" text not null primary key, "accountId" text not null, "providerId" text not null, "userId" text not null references "user" ("id") on delete cascade, "accessToken" text, "refreshToken" text, "idToken" text, "accessTokenExpiresAt" timestamptz, "refreshTokenExpiresAt" timestamptz, "scope" text, "password" text, "createdAt" timestamptz default CURRENT_TIMESTAMP not null, "updatedAt" timestamptz not null);

create table "verification" ("id" text not null primary key, "identifier" text not null, "value" text not null, "expiresAt" timestamptz not null, "createdAt" timestamptz default CURRENT_TIMESTAMP not null, "updatedAt" timestamptz default CURRENT_TIMESTAMP not null);

create table "rateLimit" ("id" text not null primary key, "key" text not null unique, "count" integer not null, "lastRequest" bigint not null);

create index "session_userId_idx" on "session" ("userId");

create index "account_userId_idx" on "account" ("userId");

create index "verification_identifier_idx" on "verification" ("identifier");

-- ---------------------------------------------------------------------
-- PART 2 · Your boards and items
-- ---------------------------------------------------------------------

-- A board is a collection, like "Packaging" or "Type specimens".
create table boards (
  id          uuid primary key default gen_random_uuid(),
  -- Whose board it is: the Better Auth user id. "references" makes it a
  -- foreign key: Postgres refuses a user_id that isn't a real user, and
  -- "on delete cascade" deletes your boards if your account is deleted.
  user_id     text not null references "user" (id) on delete cascade,
  title       text not null check (char_length(btrim(title)) between 1 and 120),
  description text not null default '' check (char_length(description) <= 1000),
  -- Private unless you make it public.
  is_public   boolean not null default false,
  created_at  timestamptz not null default now()
);

-- An item is one saved thing on a board: a picture, a link, or both.
create table items (
  id         uuid primary key default gen_random_uuid(),
  -- "on delete cascade": deleting a board deletes all of its items too.
  board_id   uuid not null references boards (id) on delete cascade,
  user_id    text not null references "user" (id) on delete cascade,
  image_url  text check (char_length(image_url) <= 2048),
  link_url   text check (char_length(link_url) <= 2048),
  title      text not null default '' check (char_length(title) <= 200),
  note       text not null default '' check (char_length(note) <= 2000),
  created_at timestamptz not null default now(),
  -- Every item needs at least a picture or a link.
  constraint items_image_or_link check (image_url is not null or link_url is not null)
);

-- Indexes are like the index at the back of a book: they let Postgres jump
-- straight to "the boards of this user" or "the items of this board"
-- instead of reading every row. Each one also keeps the rows sorted newest
-- first, which is the order the pages show them in.
create index boards_user_id_idx on boards (user_id, created_at desc);
create index items_board_id_idx on items (board_id, created_at desc);
create index items_user_id_idx on items (user_id);

-- ---------------------------------------------------------------------
-- PART 3 · Lock Supabase's automatic API out of these tables
--
-- Supabase can also share tables in the "public" schema through its own
-- web API (the "Data API"), which anyone with your project's public
-- anon/publishable key could call. This prototype doesn't use that API: it
-- connects directly with DATABASE_URL, as the "postgres" user that owns
-- these tables. Switching on Row Level Security without adding any
-- policies means the Data API sees no rows at all, while the table owner
-- (this app) still can. Without this, your users' emails and password
-- hashes could be readable through that API.
-- ---------------------------------------------------------------------

alter table "user" enable row level security;
alter table "session" enable row level security;
alter table "account" enable row level security;
alter table "verification" enable row level security;
alter table "rateLimit" enable row level security;
alter table boards enable row level security;
alter table items enable row level security;

-- ---------------------------------------------------------------------
-- PART 4 · Say "no" to the Data API explicitly
--
-- Supabase's security advisor flags tables with RLS on but no policies,
-- because it can't tell that was on purpose. These policies make it
-- explicit: the "anon" and "authenticated" roles (visitors using Supabase's
-- own API) never see or change a row. The revoke line takes away their
-- permission to touch the tables at all. This app connects as "postgres",
-- the tables' owner, so it isn't affected. (db/migrations/0004)
-- ---------------------------------------------------------------------

create policy "No Data API access" on "user" for all to anon, authenticated using (false) with check (false);
create policy "No Data API access" on "session" for all to anon, authenticated using (false) with check (false);
create policy "No Data API access" on "account" for all to anon, authenticated using (false) with check (false);
create policy "No Data API access" on "verification" for all to anon, authenticated using (false) with check (false);
create policy "No Data API access" on "rateLimit" for all to anon, authenticated using (false) with check (false);
create policy "No Data API access" on boards for all to anon, authenticated using (false) with check (false);
create policy "No Data API access" on items for all to anon, authenticated using (false) with check (false);

revoke all on "user", "session", "account", "verification", "rateLimit", boards, items from anon, authenticated;

commit;
